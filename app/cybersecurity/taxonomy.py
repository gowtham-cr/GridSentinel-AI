def decompose_class(class_id: int) -> Dict[str, Any]:
    """
    Decomposes a Mendeley IEEE 14-bus class ID (0-30) into its constituent attack properties:
    - injection_method: 'Additive', 'Deductive', 'Combined', or 'None'
    - target_strategy: 'random_node', 'vulnerable_node', or 'None'
    - temporal_pattern: 'step', 'ramp', 'pulse', 'random', 'replay', or 'normal'
    - affected_component: 'Bus_4', 'Random Bus', or 'None'
    - is_attack: True if class_id > 0 else False
    """
    if class_id in OFFICIAL_LABEL_TAXONOMY:
        return OFFICIAL_LABEL_TAXONOMY[class_id].copy()
    
    # Fallback for unknown classes
    return {
        "class_id": class_id,
        "name": f"Unknown_Class_{class_id}",
        "is_attack": class_id > 0,
        "injection_method": "Unknown",
        "target_strategy": "Unknown",
        "temporal_pattern": "unknown",
        "target_component": "Unknown",
        "default_severity": "HIGH" if class_id > 0 else "LOW",
        "description": f"Unrecognized class identifier {class_id}.",
    }

